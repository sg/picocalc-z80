/* DAZZLER stuff */
int dazzler_state;
volatile bool first_flag;
static WORD dma_addr;
static BYTE flags = 64;
static BYTE format;

#define SPLASH_COLOR RGB(180, 40, 40)

/*
 * The Dazzler is 128x128, and the PicoCalc panel is square, so it goes up at
 * exactly 2x and still leaves a 32 pixel margin - a better fit than the real
 * hardware ever had on a 4:3 television.
 */
#define DAZ_DIM	128
#define SCALE	2
#define XOFF	((LCD_WIDTH - DAZ_DIM * SCALE) / 2)
#define YOFF	((LCD_HEIGHT - DAZ_DIM * SCALE) / 2)

/*
 * Frames are composed here rather than sent pixel by pixel. The scan order
 * below walks the display memory in quadrants, not in scanlines, and every
 * one of those pixels would otherwise cost its own column and row address
 * command on the way to the panel.
 */
static uint16_t frame[DAZ_DIM * DAZ_DIM];
static uint16_t rowbuf[DAZ_DIM * SCALE * SCALE];

static inline void pixel(uint16_t x, uint16_t y, uint16_t color)
{
	frame[y * DAZ_DIM + x] = color;
}

#define BLACK 0x0000

/*
 * Interrupts are held off for one row at a time. Core 0 services core 1's
 * drawing from an interrupt, and letting that land in the middle of a region
 * write would desynchronise the panel; a row bounds the latency at about
 * 100us rather than a whole frame.
 */
/*
 * Clearing all 480 lines in one go would mask interrupts for about 33ms,
 * which stalls core 1 behind a full FIFO, so it goes a band at a time.
 */
static void clear_screen(void)
{
	int y;
	uint32_t save;

	for (y = 0; y < MEM_HEIGHT; y += 16) {
		save = save_and_disable_interrupts();
		lcd_fill(BLACK, 0, y, LCD_WIDTH, 16);
		restore_interrupts(save);
	}
}

static void blit(void)
{
	int x, y;
	uint32_t save;

	for (y = 0; y < DAZ_DIM; y++) {
		const uint16_t *src = frame + y * DAZ_DIM;

		for (x = 0; x < DAZ_DIM; x++) {
			rowbuf[x * SCALE] = src[x];
			rowbuf[x * SCALE + 1] = src[x];
		}
		memcpy(rowbuf + DAZ_DIM * SCALE, rowbuf,
		       DAZ_DIM * SCALE * sizeof(uint16_t));

		save = save_and_disable_interrupts();
		lcd_draw(rowbuf, XOFF, YOFF + y * SCALE,
			 DAZ_DIM * SCALE, SCALE);
		restore_interrupts(save);
	}
}

/* draw pixels for one frame in hires */
static void __not_in_flash_func(draw_hires)(void)
{
	int x, y, i, j, c;
	WORD addr = dma_addr;
	unsigned int cmap[2];
	unsigned int c0, c1, c2, c3, c4, c5, c6, c7;

	/* set color or grayscale from lower nibble in graphics format */
	c = format & 0x0f;
	cmap[0] = BLACK;
	cmap[1] = (format & 16) ? colors[c] : grays[c];

	if (format & 32) {	/* 2048 bytes memory */
		for (j = 0; j < 128; j += 64) {
			for (i = 0; i < 128; i += 64) {
				for (y = j; y < j + 64; y += 2) {
					for (x = i; x < i + 64;) {
						c = dma_read(addr++);
						c0 = cmap[c & 1];
						c1 = cmap[(c >> 1) & 1];
						c2 = cmap[(c >> 2) & 1];
						c3 = cmap[(c >> 3) & 1];
						c4 = cmap[(c >> 4) & 1];
						c5 = cmap[(c >> 5) & 1];
						c6 = cmap[(c >> 6) & 1];
						c7 = cmap[(c >> 7) & 1];
						pixel(x, y, c0);
						pixel(x + 1, y, c1);
						pixel(x, y + 1, c2);
						pixel(x + 1, y + 1, c3);
						x += 2;
						pixel(x, y, c4);
						pixel(x + 1, y, c5);
						pixel(x, y + 1, c6);
						pixel(x + 1, y + 1, c7);
						x += 2;
					}
				}
			}
		}
	} else {		/* 512 bytes memory */
		for (j = 0; j < 128; j += 4) {
			for (i = 0; i < 128; i += 8) {
				c = dma_read(addr++);
				c0 = cmap[c & 1];
				c1 = cmap[(c >> 1) & 1];
				c2 = cmap[(c >> 2) & 1];
				c3 = cmap[(c >> 3) & 1];
				c4 = cmap[(c >> 4) & 1];
				c5 = cmap[(c >> 5) & 1];
				c6 = cmap[(c >> 6) & 1];
				c7 = cmap[(c >> 7) & 1];
				for (y = j; y < j + 4; y += 2) {
					for (x = i; x < i + 8;) {
						pixel(x, y, c0);
						pixel(x + 1, y, c1);
						pixel(x, y + 1, c2);
						pixel(x + 1, y + 1, c3);
						x += 2;
						pixel(x, y, c4);
						pixel(x + 1, y, c5);
						pixel(x, y + 1, c6);
						pixel(x + 1, y + 1, c7);
						x += 2;
					}
				}
			}
		}
	}
}

/* draw pixels for one frame in lowres */
static void __not_in_flash_func(draw_lowres)(void)
{
	int x, y, i, j, c;
	WORD addr = dma_addr;
	const uint16_t *cmap;
	unsigned int c0, c1;

	cmap = (format & 16) ? colors : grays;
	/* get size of DMA memory and draw the pixels */
	if (format & 32) {	/* 2048 bytes memory */
		for (j = 0; j < 128; j += 64) {
			for (i = 0; i < 128; i += 64) {
				for (y = j; y < j + 64; y += 2) {
					for (x = i; x < i + 64;) {
						c = dma_read(addr++);
						c0 = cmap[c & 0x0f];
						c1 = cmap[(c >> 4) & 0x0f];
						pixel(x, y, c0);
						pixel(x + 1, y, c0);
						pixel(x, y + 1, c0);
						pixel(x + 1, y + 1, c0);
						x += 2;
						pixel(x, y, c1);
						pixel(x + 1, y, c1);
						pixel(x, y + 1, c1);
						pixel(x + 1, y + 1, c1);
						x += 2;
					}
				}
			}
		}
	} else {		/* 512 bytes memory */
		for (j = 0; j < 128; j += 4) {
			for (i = 0; i < 128; i += 8) {
				c = dma_read(addr++);
				c0 = cmap[c & 0x0f];
				c1 = cmap[(c >> 4) & 0x0f];
				for (y = j; y < j + 4; y += 2) {
					for (x = i; x < i + 8;) {
						pixel(x, y, c0);
						pixel(x + 1, y, c0);
						pixel(x, y + 1, c0);
						pixel(x + 1, y + 1, c0);
						x += 2;
						pixel(x, y, c1);
						pixel(x + 1, y, c1);
						pixel(x, y + 1, c1);
						pixel(x + 1, y + 1, c1);
						x += 2;
					}
				}
			}
		}
	}
}

static void __no_inline_not_in_flash_func(draw_bitmap)(const uint8_t *bitmap,
						       int width, int height,
						       int x, int y)
{
	int i, j;
	uint8_t m;

	for (j = 0; j < height; j++) {
		m = 0x80;
		for (i = 0; i < width; i++) {
			if (*bitmap & m)
				lcd_point(SPLASH_COLOR, x, y);
			if ((m >>= 1) == 0) {
				m = 0x80;
				bitmap++;
			}
			x++;
		}
		if (width & 7)
			bitmap++;
		x -= width;
		y++;
	}
}

void __not_in_flash_func(dazzler_draw)(void)
{
	if (first_flag) {
		uint32_t save;

		/* the cursor blink would otherwise punch through the image */
		save = save_and_disable_interrupts();
		term_set_blinking_cursor(false);
		/* the terminal leaves the scroll register wherever it got to */
		lcd_scroll(0);
		restore_interrupts(save);

		clear_screen();

		save = save_and_disable_interrupts();
		draw_bitmap(cromemco, CROMEMCO_WIDTH, CROMEMCO_HEIGHT,
			    40, (LCD_HEIGHT - CROMEMCO_HEIGHT) / 2);
		draw_bitmap(dazzler, DAZZLER_WIDTH, DAZZLER_HEIGHT,
			    LCD_WIDTH - 40 - DAZZLER_WIDTH,
			    (LCD_HEIGHT - DAZZLER_HEIGHT) / 2);
		restore_interrupts(save);

		memset(frame, 0, sizeof(frame));
		first_flag = false;
		return;
	}

	if (format & 64)
		draw_hires();
	else
		draw_lowres();

	blit();

	/* frame done, set frame flag for 4ms */
	flags = 0;
	sleep_ms(4);
	flags = 64;
}

/*
 * Called from the core 0 idle loop. Nothing else runs there, so the frame
 * rate is whatever the blit and the emulated frame flag allow.
 */
void dazzler_poll(void)
{
	if (dazzler_state)
		dazzler_draw();
	else if (first_flag) {
		/* handing the screen back to the terminal */
		uint32_t save;

		first_flag = false;
		clear_screen();
		/* term_clear() would repeat the whole-screen fill undone
		   above, so reset the terminal's own state instead */
		save = save_and_disable_interrupts();
		term_reset();
		term_set_blinking_cursor(true);
		restore_interrupts(save);
		status_paint();
	}
}

void dazzler_ctl_out(BYTE data)
{
	/* get DMA address for display memory */
	dma_addr = (data & 0x7f) << 9;

	/* switch DAZZLER on/off */
	if (data & 128) {
		if (dazzler_state == 0) {
			dazzler_state = 1;
			first_flag = true;
		}
	} else {
		if (dazzler_state == 1) {
			dazzler_state = 0;
			first_flag = true;
		}
	}
}

BYTE dazzler_flags_in(void)
{
	return flags;
}

void dazzler_format_out(BYTE data)
{
	format = data;
}
