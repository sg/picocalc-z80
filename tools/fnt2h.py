#!/usr/bin/env python3
"""
Turn a .FNT file into drivers/default_font.h, the font compiled into the
firmware and used when no font file is configured or it cannot be read.

    python3 tools/fnt2h.py sd_files/Z80/5X9.FNT drivers/default_font.h
"""

import os
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: fnt2h.py <font.FNT> <header.h>')
    data = open(sys.argv[1], 'rb').read()
    count, first, width, height, per = data[2:7]
    glyphs = data[7:7 + count * per]
    if len(glyphs) != count * per:
        sys.exit('%s: truncated' % sys.argv[1])

    out = ['/* generated by tools/fnt2h.py from %s */' % os.path.basename(sys.argv[1]),
           '#define DEFAULT_GLYPH_COUNT %d' % count,
           '#define DEFAULT_FIRSTCODE %d' % first,
           '#define DEFAULT_GLYPH_WIDTH %d' % width,
           '#define DEFAULT_GLYPH_HEIGHT %d' % height,
           '',
           'static const unsigned char default_glyphs[] = {']
    for i in range(count):
        code = first + i
        row = ', '.join('0x%02x' % b for b in glyphs[i * per:(i + 1) * per])
        label = chr(code) if 32 < code < 127 and chr(code) not in '\\*/' else '%d' % code
        out.append('\t%s,\t/* %s */' % (row, label))
    out.append('};')
    with open(sys.argv[2], 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
